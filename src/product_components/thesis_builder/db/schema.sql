-- ThesisBuilder physical schema (PostgreSQL)

CREATE SCHEMA IF NOT EXISTS thesis_builder;

CREATE TABLE IF NOT EXISTS thesis_builder.t_news_analyses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    article_id TEXT NOT NULL REFERENCES news_fetcher.t_news_articles(id),
    ticker TEXT NOT NULL,
    exchange_code TEXT NOT NULL,
    sentiment DOUBLE PRECISION NOT NULL,
    relevance DOUBLE PRECISION NOT NULL,
    urgency TEXT NOT NULL,
    suggested_action TEXT NOT NULL,
    strategy TEXT,
    direction TEXT,
    event_type TEXT,
    price_impact_magnitude TEXT,
    reasoning TEXT,
    confidence DOUBLE PRECISION NOT NULL,
    market_context_status TEXT,
    market_context_as_of TIMESTAMPTZ,
    market_context_snapshot JSONB,
    validation_status TEXT NOT NULL DEFAULT 'valid',
    validation_errors JSONB NOT NULL DEFAULT '[]'::jsonb,
    rejection_reason_code TEXT,
    llm_model TEXT NOT NULL,
    tokens_used BIGINT,
    analyzed_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_news_analyses_confidence
        CHECK (confidence >= 0 AND confidence <= 1),
    CONSTRAINT ck_news_analyses_relevance
        CHECK (relevance >= 0 AND relevance <= 1),
    CONSTRAINT ck_news_analyses_strategy
        CHECK (
            strategy IS NULL
            OR strategy IN (
                'event_driven',
                'sentiment_momentum',
                'sector_rotation',
                'contrarian_reversal',
                'trend_follow'
            )
        ),
    CONSTRAINT ck_news_analyses_direction
        CHECK (direction IS NULL OR direction IN ('buy', 'sell', 'hold')),
    CONSTRAINT ck_news_analyses_price_impact
        CHECK (price_impact_magnitude IS NULL OR price_impact_magnitude IN ('low', 'medium', 'high')),
    CONSTRAINT ck_news_analyses_market_context_status
        CHECK (market_context_status IS NULL OR market_context_status IN ('fresh', 'delayed', 'stale', 'missing')),
    CONSTRAINT ck_news_analyses_validation_status
        CHECK (validation_status IN ('valid', 'rejected'))
);

