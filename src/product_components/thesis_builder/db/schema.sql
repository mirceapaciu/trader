CREATE INDEX IF NOT EXISTS ix_news_analyses_article
    ON thesis_builder.t_news_analyses (article_id);

CREATE INDEX IF NOT EXISTS ix_news_analyses_instrument_analyzed
    ON thesis_builder.t_news_analyses (ticker, exchange_code, analyzed_at DESC);

CREATE INDEX IF NOT EXISTS ix_news_analyses_strategy_direction
    ON thesis_builder.t_news_analyses (ticker, exchange_code, strategy, direction, validation_status);

CREATE TABLE IF NOT EXISTS thesis_builder.t_evidence_windows (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticker TEXT NOT NULL,
    exchange_code TEXT NOT NULL,
    strategy TEXT NOT NULL,
    direction TEXT,
    article_ids JSONB NOT NULL DEFAULT '[]'::jsonb,
    analysis_ids JSONB NOT NULL DEFAULT '[]'::jsonb,
    window_started_at TIMESTAMPTZ NOT NULL,
    last_evidence_at TIMESTAMPTZ NOT NULL,
    status TEXT NOT NULL,
    status_reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_evidence_windows_strategy
        CHECK (
            strategy IN (
                'event_driven',
                'sentiment_momentum',
                'sector_rotation',
                'contrarian_reversal',
                'trend_follow'
            )
        ),
    CONSTRAINT ck_evidence_windows_direction
        CHECK (direction IS NULL OR direction IN ('buy', 'sell', 'hold')),
    CONSTRAINT ck_evidence_windows_status
        CHECK (status IN ('collecting', 'satisfied', 'expired', 'rejected'))
);

CREATE INDEX IF NOT EXISTS ix_evidence_windows_instrument_status
    ON thesis_builder.t_evidence_windows (ticker, exchange_code, status, updated_at DESC);

CREATE UNIQUE INDEX IF NOT EXISTS uq_evidence_windows_collecting
    ON thesis_builder.t_evidence_windows (ticker, exchange_code, strategy, COALESCE(direction, ''))
    WHERE status = 'collecting';

CREATE INDEX IF NOT EXISTS ix_evidence_windows_expiry_scan
    ON thesis_builder.t_evidence_windows (status, window_started_at)
    WHERE status = 'collecting';

CREATE TABLE IF NOT EXISTS thesis_builder.t_thesis_cards (
    id TEXT PRIMARY KEY,
    idempotency_key TEXT NOT NULL UNIQUE,
    ticker TEXT NOT NULL,
    exchange_code TEXT NOT NULL,
    direction TEXT NOT NULL,
    time_horizon TEXT NOT NULL,
    strategy TEXT NOT NULL,
    evidence JSONB NOT NULL,
    source_analysis_ids JSONB NOT NULL DEFAULT '[]'::jsonb,
    confidence DOUBLE PRECISION NOT NULL,
    risk_max_loss_usd DOUBLE PRECISION NOT NULL,
    risk_stop_condition TEXT NOT NULL,
    risk_invalidation_condition TEXT NOT NULL,
    market_context_status TEXT,
    market_context_as_of TIMESTAMPTZ,
    market_context_snapshot JSONB,
    validation_status TEXT NOT NULL,
    validation_errors JSONB NOT NULL DEFAULT '[]'::jsonb,
    signal_published_at TIMESTAMPTZ,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_thesis_cards_direction
        CHECK (direction IN ('buy', 'sell', 'hold')),
    CONSTRAINT ck_thesis_cards_strategy
        CHECK (
            strategy IN (
                'event_driven',
                'sentiment_momentum',
                'sector_rotation',
                'contrarian_reversal',
                'trend_follow'
            )
        ),
    CONSTRAINT ck_thesis_cards_confidence
        CHECK (confidence >= 0 AND confidence <= 1),
    CONSTRAINT ck_thesis_cards_risk_max_loss
        CHECK (risk_max_loss_usd >= 0),
    CONSTRAINT ck_thesis_cards_market_context_status
        CHECK (market_context_status IS NULL OR market_context_status IN ('fresh', 'delayed', 'stale', 'missing')),
    CONSTRAINT ck_thesis_cards_validation_status
        CHECK (validation_status IN ('valid', 'rejected'))
);

CREATE INDEX IF NOT EXISTS ix_thesis_cards_instrument_created
    ON thesis_builder.t_thesis_cards (ticker, exchange_code, created_at DESC);

CREATE INDEX IF NOT EXISTS ix_thesis_cards_validation_expiry
    ON thesis_builder.t_thesis_cards (validation_status, expires_at);

CREATE INDEX IF NOT EXISTS ix_thesis_cards_unpublished_valid
    ON thesis_builder.t_thesis_cards (created_at)
    WHERE validation_status = 'valid' AND signal_published_at IS NULL;
